import {
  EMPTY_SERVICE_RPC_PATCHES,
} from './cursor-proto-config.mjs';
import {
  fieldToProto,
  fieldTypeRef,
  localTypeName,
  splitFields,
} from './cursor-proto-descriptors.mjs';

/**
 * Render extracted descriptors as a deterministic proto file.
 *
 * @param {{ symToType: Map<string, string>, messageFieldsBlob: Map<string, string>, enumValues: Map<string, Array<{ name: string, number: number }>>, services: Map<string, { methods: Array<{ name: string, I: string, O: string, kind: string }> }> }} descriptors
 * @param {{ packageId: string, fileName: string, goPackage: string, imports?: string[] }} pkg
 */
export function generateProto(descriptors, pkg) {
  const { symToType, messageFieldsBlob, enumValues, services } = descriptors;
  const prefix = pkg.packageId;
  const lines = [
    '// Generated by scripts/extract-cursor-protos.mjs — do not edit by hand.',
    '// Source: Cursor extensionHostProcess.js (@bufbuild/protobuf descriptors)',
    'syntax = "proto3";',
    `package ${prefix};`,
    `option go_package = "${pkg.goPackage}";`,
  ];

  for (const importPath of pkg.imports ?? []) {
    lines.push(`import "${importPath}";`);
  }
  lines.push('');

  const inPackage = (fullName) => fullName.startsWith(`${prefix}.`);

  for (const [fullName, values] of [...enumValues.entries()]
    .filter(([name]) => inPackage(name))
    .sort((a, b) => a[0].localeCompare(b[0]))) {
    const name = localTypeName(fullName, prefix);
    lines.push(`enum ${name} { // ${fullName}`);
    values.forEach(({ name: value, number }, index) => {
      const prefixed =
        value.startsWith(`${name}_`) || value.startsWith(`${name.toUpperCase()}_`)
          ? value
          : `${name}_${value}`;
      lines.push(`  ${prefixed} = ${number ?? index};`);
    });
    lines.push('}', '');
  }

  for (const [fullName, fieldsBlob] of [...messageFieldsBlob.entries()]
    .filter(([name]) => inPackage(name))
    .sort((a, b) => a[0].localeCompare(b[0]))) {
    const name = localTypeName(fullName, prefix);
    lines.push(`message ${name} { // ${fullName}`);
    for (const field of splitFields(fieldsBlob)) {
      const declaration = fieldToProto(field, symToType, prefix);
      if (declaration) {
        lines.push(`  ${declaration}`);
      }
    }
    lines.push('}', '');
  }

  for (const [fullName, service] of [...services.entries()]
    .filter(([name]) => inPackage(name))
    .sort((a, b) => a[0].localeCompare(b[0]))) {
    const name = localTypeName(fullName, prefix);
    lines.push(`service ${name} { // ${fullName}`);
    const patchedMethods =
      service.methods.length === 0 ? EMPTY_SERVICE_RPC_PATCHES[fullName] : undefined;
    for (const patch of patchedMethods ?? []) {
      const input = fieldTypeRef(patch.in, prefix);
      const output = fieldTypeRef(patch.out, prefix);
      lines.push(`  rpc ${patch.name}(${input}) returns (${output}) {}`);
    }

    for (const method of service.methods) {
      const inputType = symToType.get(method.I);
      const outputType = symToType.get(method.O);
      if (!inputType || !outputType) {
        lines.push(`  // rpc ${method.name} skipped (unresolved request/response types)`);
        continue;
      }
      const input = fieldTypeRef(inputType, prefix);
      const output = fieldTypeRef(outputType, prefix);
      const returns =
        method.kind === 'ServerStreaming' || method.kind === 'BiDiStreaming'
          ? `stream ${output}`
          : output;
      const params = method.kind === 'BiDiStreaming' ? `stream ${input}` : input;
      lines.push(`  rpc ${method.name}(${params}) returns (${returns}) {}`);
    }
    lines.push('}', '');
  }

  return `${lines.join('\n')}\n`;
}
